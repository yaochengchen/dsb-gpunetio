#!/usr/bin/env python3
"""Comparisons between tags of results/net.csv that the text quotes.

    python3 analysis/compare.py [--net results/net.csv] [--out analysis/compare.md]

The last run of a configuration under a tag is used (as in make_tables.py).
Sections:
  1. GPU-initiated server (doca_w2t) against the faster tuned CPU server,
     per unloaded configuration (median and 99th percentile, residence, remainder)
  2. effect of the receive timeout: doca_w2 (5 us) -> doca_w2t (500 ns)
  3. effect of the send path: doca_fast (-W 0) -> doca_w2 (-W 2)
  4. host state for the GPU-initiated server: doca (default) vs doca_fast (tuned),
     and doca_w2t_def vs doca_w2t if present
  5. reruns: every tag <series>_r<k> against the original <series> run
  6. the idle-gap diagnostic runs (tag diag_w2t), if present
"""
import argparse
import csv
import re
from collections import defaultdict

FMT = {"1": "pm1", "2": "ternary", "3": "int8"}


def key(r):
    return (FMT.get(r["format"], r["format"]), int(r["n"]), int(r["B"]), int(r["K"]), int(float(r["rate"])), int(r["window"]))


def load(path):
    """by[tag][config] = last row of that tag (every tag, reruns included), and
    cur[series][config] = the NEWEST run of the configuration, where reruns are
    tagged <series>_r<k> and never overwrite the original rows."""
    with open(path) as fh:
        rows = [r for r in csv.DictReader(fh) if r.get("SUMMARY") == "SUMMARY"]
    by = defaultdict(dict)
    best = {}
    for i, r in enumerate(rows):
        by[r["tag"]][key(r)] = r
        m = re.match(r"(.+)_r(\d+)$", r["tag"])
        series, gen = (m.group(1), int(m.group(2))) if m else (r["tag"], 1)
        k = (series, key(r))
        if k not in best or (gen, i) > best[k][0]:
            best[k] = ((gen, i), r)
    cur = defaultdict(dict)
    for (series, kk), (_, r) in best.items():
        cur[series][kk] = r
    return by, cur


def f(r, c):
    return float(r[c])


def cfg(k):
    s = f"{k[0]} n={k[1]} B={k[2]} K={k[3]}"
    if k[4]:
        s += f" Poisson {k[4] // 1000}k"
    elif k[5] != 1:
        s += f" window {k[5]}"
    return s


def diff_table(by, a, b, title, L, unloaded_only=False):
    if a not in by or b not in by:
        return
    L += [f"## {title}", "", f"| config | {a} p50 | {b} p50 | Δp50 | {a} p99 | {b} p99 | Δp99 | {a} rest | {b} rest |",
          "|---|---|---|---|---|---|---|---|---|"]
    d50 = []
    for k in sorted(set(by[a]) & set(by[b])):
        if unloaded_only and (k[4] or k[5] != 1):
            continue
        ra, rb = by[a][k], by[b][k]
        x, y = f(rb, "p50_us") - f(ra, "p50_us"), f(rb, "p99_us") - f(ra, "p99_us")
        d50.append(x)
        L.append(f"| {cfg(k)} | {ra['p50_us']} | {rb['p50_us']} | {x:+.1f} | {ra['p99_us']} | {rb['p99_us']} | {y:+.1f} | {ra['net_p50_us']} | {rb['net_p50_us']} |")
    if d50:
        L += ["", f"Δp50 ({b} − {a}) over {len(d50)} configurations: min {min(d50):+.1f}, max {max(d50):+.1f} µs.", ""]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--net", default="results/net.csv")
    ap.add_argument("--out", default="analysis/compare.md")
    a = ap.parse_args()
    orig, by = load(a.net)
    L = ["# Comparisons between runs", "", "Generated by analysis/compare.py from results/net.csv. Sections 1-4 and 6 use the newest run of every configuration (reruns are tagged <series>_r<k>); section 5 compares each rerun with the original run. The `tag` column of section 1 names the run actually used. Times in µs.", ""]

    G = "doca_w2t"
    if G in by and "launch_fast" in by and "proxy_fast" in by:
        L += ["## 1. GPU-initiated server vs the faster tuned CPU server (unloaded)", "",
              "| config | GPUNetIO p50 | best CPU p50 | Δ | GPUNetIO p99 | best CPU p99 | GPU residence | CPU residence | GPU rest | CPU rest |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        wins = 0
        tot = 0
        for k in sorted(by[G]):
            if k[4] or k[5] != 1 or k not in by["launch_fast"] or k not in by["proxy_fast"]:
                continue
            g = by[G][k]
            c = min((by["launch_fast"][k], by["proxy_fast"][k]), key=lambda r: f(r, "p50_us"))
            d = f(g, "p50_us") - f(c, "p50_us")
            tot += 1
            wins += d < 0
            L.append(f"| {cfg(k)} ({g['tag']}) | {g['p50_us']} | {c['p50_us']} ({c['tag']}) | {d:+.1f} | {g['p99_us']} | {c['p99_us']} | "
                     f"{g['srv_p50_us']} | {c['srv_p50_us']} | {g['net_p50_us']} | {c['net_p50_us']} |")
        L += ["", f"GPU-initiated server faster in {wins} of {tot} configurations.", ""]
        L += ["### Under load (reference configuration)", "", "| offered | tag | achieved kreq/s | lost | p50 | p99 | p99.9 |", "|---|---|---|---|---|---|---|"]
        for t in (G, "proxy_fast", "launch_fast"):
            for k in sorted(by.get(t, {})):
                if k[:4] == ("int8", 128, 8, 100) and k[4]:
                    r = by[t][k]
                    L.append(f"| {k[4] // 1000}k | {t} | {r['kreq_s']} | {r['lost']} | {r['p50_us']} | {r['p99_us']} | {r['p999_us']} |")
        L.append("")

    diff_table(by, "doca_w2", "doca_w2t", "2. Receive timeout 5 µs (doca_w2) → 500 ns (doca_w2t)", L)
    diff_table(by, "doca_fast", "doca_w2", "3. Send path per-reply (-W 0, doca_fast) → batched (-W 2, doca_w2)", L)
    diff_table(by, "doca", "doca_fast", "4a. GPU-initiated server, default host (doca) → tuned host (doca_fast), -W 0", L, unloaded_only=True)
    diff_table(by, "doca_w2t", "doca_w2t_def", "4b. GPU-initiated server, tuned (doca_w2t) → default host (doca_w2t_def)", L, unloaded_only=True)
    for t in sorted(orig):
        m = re.match(r"(.+)_r\d+$", t)
        if m and m.group(1) in orig:
            diff_table(orig, m.group(1), t, f"5. Rerun: {m.group(1)} (original) → {t} (new)", L)
    if "diag_w2t" in by:
        L += ["## 6. Idle-gap diagnostic (diag_w2t, closed loop, 1 outstanding)", "",
              "| config | server residence p50 | remainder p50 | RTT p50 | RTT p99 |", "|---|---|---|---|---|"]
        for k in sorted(by["diag_w2t"], key=lambda k: f(by["diag_w2t"][k], "srv_p50_us")):
            if k[4] or k[5] != 1:
                continue
            r = by["diag_w2t"][k]
            L.append(f"| {cfg(k)} | {r['srv_p50_us']} | {r['net_p50_us']} | {r['p50_us']} | {r['p99_us']} |")
        L.append("")
    with open(a.out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
