#!/usr/bin/env python3
"""Request service on two GPU platforms: server on PU2 (RTX PRO 6000, client PU3, results/net.csv) against
server on PU3 (GH200, client PU2 over the same cable, results/pu3srv/net.csv).

    python3 supplementary_revision/analysis/compare_pu3srv.py [--ref results/net.csv] [--new supplementary_revision/results/pu3srv/net.csv]
                                       [--out supplementary_revision/tables/pu3srv_compare.md]

Run from the repository root.  Like analysis/compare.py (whose load() it uses), the NEWEST run of every
configuration of a series is reported (reruns are tagged <series>_r<k>); the tag actually used is printed.
Sections:
  1. GPUNetIO server, unloaded: PU2 (doca_w2t) vs PU3 (pu3srv_doca_w2t): RTT, server residence, remainder
  2. reference configuration int8 n=128 B=8 K=100 under load, every series of both files
  3. PU3: GPUNetIO vs the CPU baselines measured there (if pu3srv_launch_fast / pu3srv_proxy_fast exist)
Times in microseconds.
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "analysis"))
from compare import load, cfg, f  # noqa: E402  (the unchanged analysis/compare.py of this repository)

REF_G = "doca_w2t"
REF_CPU = ("launch_fast", "proxy_fast", "launch", "proxy")


def unloaded(k):
    return not k[4] and k[5] == 1


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", default="results/net.csv", help="PU2-server results (unchanged)")
    ap.add_argument("--new", default="supplementary_revision/results/pu3srv/net.csv", help="PU3-server results")
    ap.add_argument("--new-series", default="pu3srv", help="series prefix of the PU3-server runs")
    ap.add_argument("--out", default="supplementary_revision/tables/pu3srv_compare.md")
    a = ap.parse_args()
    _, ref = load(a.ref)
    _, new = load(a.new)
    P = a.new_series
    G = f"{P}_doca_w2t"
    L = ["# Request service: server on PU2 (RTX PRO 6000) vs server on PU3 (GH200)", "",
         f"Generated by supplementary_revision/analysis/compare_pu3srv.py from {a.ref} and {a.new}; newest run of every configuration; "
         "the tag used is in parentheses.  rest = RTT − server residence (wire, NICs, client stack; the client host differs: PU3 in the reference, PU2 here).", ""]

    if REF_G in ref and G in new:
        L += [f"## 1. GPUNetIO server, unloaded: PU2 ({REF_G}) vs PU3 ({G})", "",
              "| config | PU2 p50 | PU3 p50 | PU2 p99 | PU3 p99 | PU2 residence | PU3 residence | residence PU3/PU2 | PU2 rest | PU3 rest |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for k in sorted(new[G]):
            if not unloaded(k) or k not in ref[REF_G]:
                continue
            r, s = ref[REF_G][k], new[G][k]
            ratio = f(s, "srv_p50_us") / f(r, "srv_p50_us") if f(r, "srv_p50_us") > 0 else float("nan")
            L.append(f"| {cfg(k)} ({r['tag']} / {s['tag']}) | {r['p50_us']} | {s['p50_us']} | {r['p99_us']} | {s['p99_us']} | "
                     f"{r['srv_p50_us']} | {s['srv_p50_us']} | {ratio:.2f} | {r['net_p50_us']} | {s['net_p50_us']} |")
        L.append("")
    else:
        L += [f"(section 1 skipped: series {REF_G} in {a.ref}: {REF_G in ref}; {G} in {a.new}: {G in new})", ""]

    L += ["## 2. Reference configuration under load (int8 n=128 B=8 K=100, Poisson)", "",
          "| server | series (tag) | offered | achieved kreq/s | lost | p50 | p99 | p99.9 | residence p50 |",
          "|---|---|---|---|---|---|---|---|---|"]
    for host, by, series in (("PU2", ref, (REF_G,) + REF_CPU), ("PU3", new, sorted(new))):
        for t in series:
            for k in sorted(by.get(t, {})):
                if k[:4] == ("int8", 128, 8, 100) and k[4]:
                    r = by[t][k]
                    L.append(f"| {host} | {t} ({r['tag']}) | {k[4] // 1000}k | {r['kreq_s']} | {r['lost']} | {r['p50_us']} | "
                             f"{r['p99_us']} | {r['p999_us']} | {r['srv_p50_us']} |")
    L.append("")

    cpus = [t for t in (f"{P}_launch_fast", f"{P}_proxy_fast", f"{P}_launch", f"{P}_proxy") if t in new]
    if G in new and cpus:
        L += [f"## 3. PU3: GPUNetIO ({G}) vs the faster CPU server measured on PU3 ({', '.join(cpus)}), unloaded", "",
              "| config | GPUNetIO p50 | best CPU p50 | Δ | GPUNetIO p99 | best CPU p99 |", "|---|---|---|---|---|---|"]
        wins = tot = 0
        for k in sorted(new[G]):
            have = [new[t][k] for t in cpus if k in new[t]]
            if not unloaded(k) or not have:
                continue
            g = new[G][k]
            c = min(have, key=lambda r: f(r, "p50_us"))
            d = f(g, "p50_us") - f(c, "p50_us")
            tot += 1
            wins += d < 0
            L.append(f"| {cfg(k)} | {g['p50_us']} | {c['p50_us']} ({c['tag']}) | {d:+.1f} | {g['p99_us']} | {c['p99_us']} |")
        L += ["", f"GPUNetIO faster in {wins} of {tot} configurations.", ""]

    bad = [(h, t, kk) for h, by in (("PU2", ref), ("PU3", new)) for t in by for kk, r in by[t].items()
           if int(r["verify_bad"]) or int(r["ref_bad"])]
    if bad:
        L += ["## Verification failures (verify_bad or ref_bad != 0) -- these rows must not be used", ""]
        L += [f"* {h} {t} {cfg(kk)}" for h, t, kk in bad]
        L.append("")
    with open(a.out, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
